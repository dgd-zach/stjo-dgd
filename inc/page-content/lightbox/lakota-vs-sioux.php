<!-- wp:paragraph -->
<p>Lakota speakers usually lived west of the Missouri River in North and South Dakota, as well as northern Nebraska, northeast Wyoming and southeast Montana. Dakota bands were located east of the Missouri River and Nakota speakers lived between these two areas, in what is now southeast South Dakota and northern Iowa.</p>
