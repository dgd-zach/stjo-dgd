<!-- wp:paragraph -->
<p>The legend of Iktómi (Ik-to-mi) comes from the Plains, Southwestern and Western Native American groups.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>From Lakota legend, Iktómi is the firstborn son of Íŋyaŋ &mdash; <em>the Rock</em> &mdash; who was originally named Ksa.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Native American culture recognized Iktómi as both a spider and a spider-like man. He was born full grown from an egg and was the size of an ordinary human. He has a big round body like a spider, with slender arms and legs and powerful hands and feet. He dresses in clothes made of buckskin and raccoon.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The Lakota believe that Iktómi is a trickster and does things backwards. His clownish ways cause the people to laugh at him, but he is also a sly and cunning man and a teacher.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>As a spider-like man, Iktómi the trickster possesses mysterious, supernatural powers &mdash; both good and bad. He might predict something, and if he senses that the people have doubts about his prediction, he makes it come true.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Native American culture boasts many stories about Iktómi the Trickster. In most stories, Iktómi comes out on top because he is so wise, cunning and sly. Because of these characteristics, sometimes he outsmarts himself.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Although most tales involve the trickster figure, the stories primarily center on morality lessons for the young. The tales of Iktómi&#8217;s mischief leads many to believe that he is an evil figure. However, this is not always the case. Iktómi can be seen as both good and bad, and has been portrayed in both ways. Iktómi is generally viewed as a being whose gaze is to be avoided, lest trouble find you.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Alternate names for Iktómi include Ikto, Ictinike, Inktomi, Unktome and Unktomi. These names are due to the differences in tribal languages, as this spider deity was known throughout many of North America&#8217;s tribes.</p>
<!-- /wp:paragraph -->

