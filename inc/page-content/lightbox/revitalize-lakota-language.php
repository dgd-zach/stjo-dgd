<p>In 2015, St. Joseph’s Indian School joined forces with the <a href="https://lakhota.org/">Lakota Language Consortium</a> to help save the Lakota language by giving our students the tools to become fluent Lakota speakers.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>LaRayne has taught St. Joseph’s Native American Studies classes for nearly two decades at St. Joseph’s and has seen the success of the new curriculum.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>“Our students want to speak Lakota,” she said. “In class when a student hears someone speaking fluently, they just smile and say, ‘Wow! Keep talking like that!’”</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In a supportive effort, we will now be following the language standards students are using in our communications with you, our generous supporters. For example, you have seen the word pilamaya — thank you. With the new spelling and diacritics, this will now be philámayaye — thank you.</p>
<!-- /wp:paragraph -->

