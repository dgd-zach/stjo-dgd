<!-- wp:paragraph -->
<p>To the Lakota, a šúŋkawakȟán &mdash; horse &mdash; is a relative. A four-legged friend and companion that provided transportation, friendship and pride. The horse is revered for its grace and bravery.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When the horse arrived to the Great Plains region, the Lakota named them šúŋkawakȟán, which translates to mysterious or sacred dog. A bond was formed between the Lakota people and the horse that still remains strong to this day. The human and horse are closely linked in Native American culture.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The Lakota were nomads. Where the tȟatȟáŋka &mdash; buffalo &mdash; went, so did the Lakota. Horses made this nomadic lifestyle of moving from place to place much more efficient. Before the Lakota had horses, they had only the šúŋka &mdash; dog &mdash; and themselves to carry heavy loads, such as the thípi. Horses, with their strong stature, eased the moving process significantly.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Horses also revolutionized hunting and warfare. Horses gave men speed they had never had before, and the ability to get as close as possible to a running buffalo, or an enemy in war.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Because of its great impact on the Lakota way of life, the horse was highly respected. For special occasions, such as a ceremony or war, a horse might be painted with symbols that were important to its owner. Some also decorated their horse&#8217;s bridles, saddles and saddle bags with beadwork or quillwork.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Native Americans honored horses by incorporating them into their cultural and spiritual lives, and by creating art that honored the bravery and grace of the horse. Many ceremonies were based on the horse and its contributions to Native American life.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Today, although life is vastly different from the days of nomadic living, the bond between Native Americans and the horse has remained strong. Lakota people still look to the horse to provide healing from trauma, anxiety, and mental and emotional distress, among others. This fact led St. Joseph&#8217;s Indian School to establish an equine therapy program in 2018. To learn more about this program and how horses are helping Lakota boys and girls at St. Joseph&#8217;s Indian School, please visit <a href="https://www.stjo.org/horses">www.stjo.org/horses</a>.</p>
<!-- /wp:paragraph -->
