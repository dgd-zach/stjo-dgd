<p class="stjo-subhead">Inappropriate behavior is unequivocally not tolerated at St. Joseph’s Indian School. A zero-tolerance policy is strictly enforced throughout our programs. In addition to internal policies, we are a member of the <a href="https://www.core-dc.org/">Coalition of Residential Excellence (CORE)</a>, which is a national organization committed to ensuring quality care for children and youth in residential communities. St. Joseph’s is accredited by the Council on Accreditation, which imposes <a href="https://coanet.org/private-standards/">rigid standards in all aspects of our organization</a>, particularly regarding the health, safety and rights of clients/students. Our elementary school is accredited by the state of South Dakota, meeting all of the educational requirements of the state.</p>
