<!-- wp:paragraph -->
<p>There are several policies in place at St. Joseph’s to protect our students from abuse.</p>
<!-- /wp:paragraph -->

<!-- wp:list --><ul class="wp-block-list"><!-- wp:list-item -->
<li>The <a href="https://www.stjo.org/sexual-misconduct-policy/">employee conduct policy</a> clearly outlines acceptable and unacceptable behavior. Violation of this policy is grounds for immediate dismissal.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>St. Joseph’s extensive hiring process requires all applicants to submit to a background check and fingerprinting. For houseparent applicants, extensive interviews are conducted by multiple staff and conclude with the candidate sharing dinner in a St. Joseph’s home with students and current houseparents. Feedback is solicited from all staff who come into contact with the candidate.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Security cameras are strategically placed in student areas, including the school, homes and rec center. Footage is reviewed daily.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>All staff are mandatory reporters.</li>
<!-- /wp:list-item --></ul><!-- /wp:list -->

<!-- wp:paragraph -->
<p>Students and staff receive annual training and education.</p>
<!-- /wp:paragraph -->

<!-- wp:list --><ul class="wp-block-list"><!-- wp:list-item -->
<li>All staff in contact with students are required to complete Safe &amp; Sacred Environment Training.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>All staff in contact with students are trained in the personal boundaries guidelines set forth by <a href="https://www.stjo.org/wp-content/Media/PDFs/Protecting-Children/PreventingChildSexualAbuseBrochure.pdf">Christian Brothers Services</a>.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Child Services staff members are trained in <a href="https://www.lsci.org/">Life Space Crisis Intervention</a>, which provides a roadmap through conflict, turning crisis situations into learning opportunities.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>To appropriately respond to a crisis, or a potential crisis, SJIS utilizes the Nonviolent Crisis Intervention Program (CPI). The organization has three certified CPI instructors. CPI’s main goal is to teach crisis prevention; staff are specifically trained in CPI’s Crisis Development Model for de-escalation. Physical restraint of a student will occur only as a last resort when staff and/or students are put in a situation of danger.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Child Services staff and student mentors receive special training in identifying victim and offender behaviors.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Students and Child Services staff participate in the Olweus Bullying Prevention Program, which works to reduce existing bullying problems, prevent new problems and support better peer relations.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Students utilize the <a href="https://www.secondstep.org/child-protection">Second Step Child Protection Unit</a> to develop staff and student knowledge and skills for protecting students from unsafe and abusive situations in and outside of school. Specific skills for recognizing and reporting abusive situations and responding in a supportive way to students who disclose abuse are also targeted.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Called to Protect educates and empowers children to protect themselves and others by recognizing and reporting any sort of suspicious behavior.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Starting in second grade, students participate in <a href="http://lakotacirclesofhope.org/">Lakota Circles of Hope</a>. With age-appropriate lessons, this curriculum is a culturally-specific approach to help students learn to protect themselves by setting clear boundaries, developing a safety plan and saying no to unhealthy relationships or behaviors. After eighth grade, high school students keep working on these skills through <a href="https://whitebison.org/youth-programs/">Daughters of Tradition and Sons of Tradition</a> groups.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Family Service Counselors complete a “Safety Checklist” with students twice each year, asking questions about specific bullying, safety and abuse issues. Any information that meets reporting criteria is reported to the Department of Social Services and/or law enforcement.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Staff follow the South Dakota Codified Law as mandatory reporters and follow the reporting protocol as established through the Department of Social Services.</li>
<!-- /wp:list-item --></ul><!-- /wp:list -->

