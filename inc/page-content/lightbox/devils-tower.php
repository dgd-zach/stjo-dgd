<!-- wp:paragraph -->
<p>According to legend, a caravan of Teton Lakota was slowly moving toward the Black Hills to harvest the many varieties of fruit abounding there. The excitement of new country, new experiences and the prospect of what lay beyond the hill held a thrill of expectation for all.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The vanguard scouts went far ahead. Their task was to blaze a trail for the others to travel, while also scouting for water facilities, hunting prospects, natural protective fortifications and good camping sites.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>After many days of marching, the Lakota caravan encountered rugged terrain. To the southeast the Black Hills appeared, hazily black. Bears were numerous in the rough piney hills, but as they rarely attacked human beings unless wounded, sick or hungry, no one feared them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Then one day, an alarm was quickly relayed through the column. Several young girls had wandered off and now were presumed to be lost. Search parties were hurriedly formed and dispatched in all directions. Finally the girls were spotted, but they were surrounded by a pack of hungry bears. The frightened children screamed for help. No one was near enough to save them. The rescuers, still too far away, looked on in horror as the growling bears closed in on the girls.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Suddenly a voice from the sky spoke to the little girls, saying pahá akíli &mdash; <em>climb the hill</em>. It had a strange effect on the attacking bears. For a time they stood paralyzed, giving the little girls a chance to scramble up a small hill.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The girls huddled together and hid their faces from the angry bears. Then, the earth shook and groaned as the little hill began to rise out of the ground, carrying the children high into the air. Higher and higher the mound rose, as the frustrated bears growled and clawed at its sides. Sharp pieces of rock broke away from the rising spire and crashed down upon the angry bears.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That was how Devils Tower came to be, according to Lakota legends. To prove it, the Lakota point to the deep crevices along the walls of the tower and the claw marks made by the huge bears of long ago. Devils Tower is also known as Matȟó Thípila to the Lakota (Sioux) which translates to <em>the bears lodge</em>.</p>
