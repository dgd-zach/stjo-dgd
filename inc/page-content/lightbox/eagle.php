<!-- wp:paragraph -->
<p>The waŋblí &mdash; eagle &mdash; is an important winged symbol for the Native American people.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The eagle is the strongest and bravest of all birds. For this reason, Native Americans have chosen the eagle and its feathers as a symbol of what is highest, bravest, strongest and holiest.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In the Native American culture, eagle feathers are given to another in honor, and the feathers are worn with dignity and pride. They are treated with great respect.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When an eagle feather is dropped during a Native American dance, a special ceremony is performed to pick it up again, and the owner is careful to never drop it again.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>An eagle feather is also used to adorn the sacred pipe because it is a symbol of the Great Spirit who is above all and from whom all strength and power flows.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Since the eagle holds high meaning in the Native American culture, eagle feathers and wings are used in special ways. For instance, when they are held over someone&#8217;s head, it means the person is brave or is wished bravery and happiness. To wave it over everyone present means everyone is wished peace, prosperity and happiness.</p>
<!-- /wp:paragraph -->

