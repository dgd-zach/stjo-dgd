<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Equal Treatment</strong> &mdash; Students have the right not to be discriminated against because of race, color, sex, language, religion, political or other opinions, national or social origin, property, birth or other status.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Necessities of Life</strong> &mdash; Students have the right to be provided with the necessities of life (clothing, sleep, shelter and nutritious food). This right MAY NOT be denied or reduced as a disciplinary measure.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Freedom of Expression</strong> &mdash; Students have the right to express their ideas and opinions. THIS RIGHT IS LIMITED. It does not imply that students can verbally abuse another individual without consequences. This right will not protect those who purposely say something to harm another. False accusations, slander or defamation of character also may result in consequences.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Protection from Abuse</strong> &mdash; Students have the right to be protected from acts or threats of harm or mistreatment from peers or staff members. This right includes the right to be free from unreasonable search and seizure of their person and property, to a reasonable degree of privacy and to a safe and secure environment.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Medical and Dental Care</strong> &mdash; All students will be provided with adequate medical and dental care as determined by qualified medical personnel.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Religious Freedom</strong> &mdash; Students have the right to hold any religious belief. Students will be required, however, to attend weekly services and regularly scheduled religious education as provided by St. Joseph&#8217;s Indian School.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Education and Recreation</strong> &mdash; Students will have the opportunity to meet their basic educational and recreational needs. In addition, students have access to recreational opportunities and equipment, including regular outdoor exercise, unless prohibited by severe weather or serious negative behavior.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Personal Appearance</strong> &mdash; Students have the right to determine their own personal appearance relating to hairstyle and clothing within the guidelines set forth within St. Joseph&#8217;s gang and dress code policies.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Right to Service</strong> &mdash; Students have the right to an individualized service plan with specific and measurable service goals. Daily living and service will include at a minimum the opportunity for academic education, physical recreation, medical care, counseling services, supervision by trained staff members and maintenance of ties with approved family members. Students&#8217; confidentiality in all records, correspondence, and conversation relating to services is protected except with written consent.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Right to Visitation</strong> &mdash; Students have the right to receive visitors as well as be checked out from St. Joseph&#8217;s. This right is subject to the discretion of staff on-duty as well as specific written St. Joseph&#8217;s policies. A request can be denied for legal reasons or when it jeopardizes the safety and security of the student or the facility.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Right to Outside Communication</strong> &mdash; Students have the right to conduct private telephone conversations within reason; depending on the location of the phone and home layout. Conversations are subject to the rules of the home and St. Joseph&#8217;s Indian School. Phone communication with specific individuals can be limited or stopped if it is negatively affecting the student or is requested by the parent or guardian of the student. Similarly, students have the right to send and receive uncensored and unopened mail. If incoming mail is suspected of containing injurious, harmful, or illegal materials or substances, the student will be required to open the mail in the presence of designated personnel. Staff members can supervise the opening of all mail when requested by the student&#8217;s parent/guardian. This action shall be documented both to sender and recipient.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Parent/Guardian/Student Grievance Procedure:</strong> Forms will be provided to a parent/guardian or student upon request to express or resolve a concern. The given process can be initiated by contacting the office of the Executive Director of Child Services either in a verbal or written form and requesting a &#8220;Grievance/Complaint&#8221; form. A resolution will be sought within 30 days of receiving the grievance.</li>
