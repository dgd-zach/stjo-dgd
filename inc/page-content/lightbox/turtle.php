<!-- wp:paragraph -->
<p>The khéya &mdash; turtle &mdash; is present in a multitude of stories, legends and observations of the Lakota (Sioux) people.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>One of these observations, for example, has to do with the scales on the turtle&#8217;s shell and the number of months in a year. Based on certain star constellations in the night sky that appeared during different seasons, the Lakota identified 13 moons throughout the year. This led to them creating their yearly calendar, which contained 13 months &mdash; each having 28 days.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The Lakota also observed some creatures on Earth reflected the same or similar natural phenomena. Like the number of moons and days each moon is present, the turtle has 13 large scales on its back, and 28 small scales around the shell &mdash; mimicking the monthly moon pattern. Because of this and other natural occurrences, the turtle became an important symbol in Lakota society.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The spirit of the turtle represents the guardian of life, longevity and fortitude. This is why the shape of a turtle was chosen to be made into an amulet. An amulet is a leather pouch decorated with beads to store a newborn&#8217;s umbilical cord. Once the newborn&#8217;s umbilical cord fell off, it was stored inside the amulet for safekeeping. Turtle shaped amulets were given to newborn baby girls and agléška &mdash; lizard &mdash; shaped amulets were given to the boys.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The amulets were put away until the children matured enough to take care of them and treat them respectfully. They were then brought out for ceremonies and special occasions &mdash; often pinned to ceremonial dress.</p>
<!-- /wp:paragraph -->
