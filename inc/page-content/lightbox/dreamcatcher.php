<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">How the Dreamcatcher Came to Be</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Long ago, when the world was young, an old Lakota spiritual leader was on a high mountain. On the mountain, he had a vision. In his vision, Iktomi &mdash; the great trickster and teacher of wisdom &mdash; appeared in the form of a spider.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Iktomi spoke to him in a sacred language that only spiritual leaders of the Lakota could understand. As Iktomi spoke, he took the elder&#8217;s willow hoop &mdash; which had feathers, horse hair, beads and offerings on it &mdash; and began to spin a web.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>He spoke to the elder about the cycles of life and how we begin our lives as infants. We then move on to childhood and in to adulthood. Finally, we go to old age where we must be taken care of as infants, thus, completing the cycle.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;But,&#8221; Iktomi said as he continued to spin his web, &#8220;in each time of life there are many forces &mdash; some good and some bad. If you listen to the good forces, they will steer you in the right direction. But, if you listen to the bad forces, they will hurt you and steer you in the wrong direction.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>He continued, &#8220;There are many forces and different directions that can help or interfere with the harmony of nature and also with the Great Spirit and all of his wonderful teachings.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>All while the spider spoke, he continued to weave his web &hellip; starting from the outside and working toward the center. When Iktomi finished speaking, he gave the Lakota elder the web and said, &#8220;See, the web is a perfect circle, but there is a hole in the center of the circle.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;Use the web to help yourself and your people &hellip; to reach your goals and make use of your people&#8217;s ideas, dreams and visions. If you believe in the Great Spirit, the web will catch your good ideas, and the bad ones will go through the hole.&#8221; (Note: Some bands believe the bad ideas are caught in the web and the good ideas pass through to the individual. Either account is acceptable.)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The Lakota elder passed his vision on to his people. Now, the Sioux use the dreamcatchers as the web of their life. Traditionally, it is hung above their beds or in their homes to sift their dreams and visions. Good dreams are captured in the web of life and carried with them &hellip; but the evil dreams escape through the center&#8217;s hole and are no longer part of them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Lakota believe the dreamcatcher holds the destiny of their future.</p>
<!-- /wp:paragraph -->

