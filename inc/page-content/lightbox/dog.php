<!-- wp:paragraph -->
<p>The šúŋka &mdash; dog &mdash; has long played an important role in Lakota society and culture. Before the arrival of the horses to the Great Plains, the Lakota (Sioux) relied heavily on dogs for a variety of tasks.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Dogs helped transport heavy loads by pulling travois, or drag sleds. These sleds were made in a similar way as the horse travois, but much smaller. They consisted of two wooden poles with a platform or basket suspended between them which was then attached to the back of the dog. The travois were used to move meat back to the village after a successful hunt. They were also used to help move campsites as the village followed buffalo herds &mdash; the tribe&#8217;s main protein source of food.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Along with being useful hunting and traveling companions, dogs took on several other roles. They watched over the children, helped keep people warm during the winter and warned the camp of intruders. They also alerted the Lakota of the dangers of rattlesnakes and other predators nearby. Simply put, they were part of the Lakota family and accepted their role with pride. Much could be learned from the companionship of our four-legged relative, such as humility and friendship.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For these reasons and more, the dog was considered sacred and greatly respected among the Lakota.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Today, the Lakota people still seek companionship with dogs &mdash; including the students at St. Joseph&#8217;s Indian School. St. Joseph&#8217;s implemented a dog program in 2017 called HAPI (Houseparents And Pets In) Homes. This program allows houseparents and other staff members the opportunity to bring their dog to campus to give students the opportunity to learn the life skill of properly caring for an animal. Also, not every student has had positive encounters with dogs because of the common stray dog issues in reservation communities. This program allows for space to repair any negative feelings toward dogs from past experiences and work toward healing for the future.</p>
<!-- /wp:paragraph -->
