<p>There is promise the Lakota language can endure. As students grow in their language skills and become fluent speakers, it can move from endangered to thriving.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>After all, the Lakota culture depends on it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>“Without language, there is no culture. We need language in our songs and our ceremonies. We need it in our hearts,” said LaRayne. “We need it in life.”</p>
<!-- /wp:paragraph -->

