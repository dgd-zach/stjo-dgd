<!-- wp:paragraph -->
<p>According to legend, two young Lakota men were chosen by their tribe to find the location of the buffalo. While the men set out in pursuit, they saw someone in the distance walking toward them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>They were on the watch for any enemy, so they hid in some bushes and waited. At last, the figure came up the slope. They discovered the figure walking toward them was a beautiful woman.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When she came closer, the woman stopped and looked at them. On her left arm, she carried what looked like a stick in a bundle of sagebrush.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>One of the men became consumed with desire to make her his wife; while the other warned him of such thoughts.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Though at a distance, the woman heard them talk. She laid down her bundle and spoke to them. &#8220;Come. What is it you wish?&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The man with desire went up to her and laid his hands on her as if to claim her. At once there came a whirlwind, followed by a mist, which hid the man and woman. When the mist cleared, the other man saw the woman with the bundle again on her arm. His friend was a pile of bones at her feet. Then, the woman spoke to him.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;I am on a journey to your people. Among them is a good man whose name is Bull Walking Upright. Go on ahead of me and tell your people I am on my way. Ask them to move camp and to pitch their tents in a circle. Ask them to leave an opening in the circle, facing the north. In the center of the circle, make a large tipi, also facing the north. There I will meet Bull Walking Upright and his people.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The man saw to it that all her directions were followed. When she reached the camp, she removed the sagebrush from the gift she was carrying. The gift was a small pipe made of red stone. On it was carved the tiny outline of a buffalo calf. She gave the pipe to Bull Walking Upright, and then she taught him the prayers he should pray to the Great Spirit.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;When you are hungry, unwrap the pipe and lay it bare in the air. Then, the buffalo will come where the men can easily hunt and kill them so the children, the men and the women will have food.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The woman also told him how the people should behave in order to live peacefully. She taught them the prayers they should say when praying to their Mother Earth. She told him how they should decorate themselves for ceremonies.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;The earth,&#8221; she said, &#8220;is your mother. So, for special ceremonies, you will decorate yourselves as your mother does &mdash; in black and red, in brown and white. These are the colors of the buffalo also.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The woman said, above all else, remember the peace pipe.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;You will smoke it before all ceremonies. You will smoke it before making treaties. It will bring peaceful thoughts into your minds. If you will use it when you pray to the Strong One Above and to Mother Earth you will be sure to receive the blessings you ask.&#8221;</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When the woman completed her message, she turned and slowly walked away. All the people watched her in awe. Outside the opening of the circle, she stopped for an instant and then lay down on the ground. She rose again in the form of a black buffalo cow. Again she lay down and then arose in the form of a red buffalo cow. A third time she lay down, and arose as a brown buffalo cow. The fourth and last time she had the form of a spotlessly white buffalo cow. Then she walked toward the north into the distance and finally disappeared over a far-off hill.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Bull Walking Upright kept the peace pipe carefully wrapped most of the time. Every little while he called all his people together, untied the bundle, and repeated the lessons he had been taught by the beautiful woman. And he used it in prayers and other ceremonies until he was more than 100 years old.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When he became feeble, he held a great feast. There he gave the pipe and the lessons to Sunrise, a worthy man. In a similar way the pipe was passed down from generation to generation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>&#8220;As long as the pipe is used,&#8221; the beautiful woman had said, &#8220;your people will live and will be happy. As soon as it is forgotten, the people will perish.&#8221;</p>
<!-- /wp:paragraph -->

