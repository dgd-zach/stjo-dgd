<p>Most Native Americans in South Dakota are associated with tribal bands like the Oglala, Sicangu, Mnicoujou and Siha Sapa, which are also part of the <a href="/lakota-culture/#oceti-sakowin-seven-council-fires">Oceti Sakowin</a> — Seven Council Fires. Together, these groups are commonly referred to as the Sioux. They are also recognized by their band’s dialect — Lakota, Dakota or Nakota.</p>
