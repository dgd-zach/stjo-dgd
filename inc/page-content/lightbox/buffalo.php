<!-- wp:paragraph -->
<p>The tȟatȟáŋka &mdash; buffalo &mdash; are held in high regard by the Lakota people. It is respected as a symbol of the divine because for Native Americans, the buffalo was a &#8220;banquet&#8221; for the people.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The buffalo &mdash; tȟatȟáŋka &mdash; gave up its own flesh and life to feed the Native American people. It provided for their every need by way of sheltering them with its hide over their tipis; covering their bodies as clothing and their feet as moccasins.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For the Native Americans, the buffalo also provided everyday utensils such as needle and thread, awls, bowls and more. In this way, the tȟatȟáŋka &mdash; buffalo &mdash; was a true relative for the people &mdash; making life possible.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Because of the American buffalo&#8217;s great importance to the people, a buffalo symbol or skull is present in all sacred Lakota rituals. It stands as a reminder of this great animal which gives completely of itself for others.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The buffalo is a symbol of self-sacrifice; it gives until there is nothing left. This was imitated by the people in their lives. To be generous and give what you have to others in need, or to honor them, is one of the most highly respected ways of behaving.</p>
